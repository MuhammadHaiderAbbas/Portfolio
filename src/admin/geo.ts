// Turns a visitor's device time zone into an approximate area for the dashboard.
// This is deliberately coarse: "Europe/London" covers the whole UK, so the map
// shows the time zone's main city, never where a visitor actually is.
import zonesData from './zones.json';
import world from './world.json';

const zones = zonesData as unknown as Record<string, [string, number, number]>;
let regionNames: Intl.DisplayNames | null = null;
try {
  regionNames = new Intl.DisplayNames(['en-GB'], { type: 'region' });
} catch {}

export interface Area {
  key: string;
  city: string;
  cc: string;
  country: string;
  lat: number | null;
  lon: number | null;
}

export const flag = (cc: string) =>
  /^[A-Z]{2}$/.test(cc) ? String.fromCodePoint(...[...cc].map((c) => 127397 + c.charCodeAt(0))) : '🌐';

export function countryName(cc: string): string {
  if (!cc) return 'Unknown';
  try {
    return regionNames?.of(cc) ?? cc;
  } catch {
    return cc;
  }
}

export function area(tz: string): Area {
  const z = zones[tz];
  const city = (tz.split('/').pop() || tz || 'Unknown').replace(/_/g, ' ');
  if (!z) return { key: tz || 'unknown', city: tz ? city : 'Unknown', cc: '', country: 'Unknown', lat: null, lon: null };
  return { key: tz, city, cc: z[0], country: countryName(z[0]), lat: z[1], lon: z[2] };
}

export const areaLabel = (a: Area) => (a.cc ? `${a.city}, ${a.country}` : a.city);

export const map = world as { w: number; h: number; k: number; tx: number; ty: number; d: string };

/** Natural Earth projection, matching the outline generated by scripts/gen-geo.mjs. */
export function project(lon: number, lat: number): [number, number] {
  const l = (lon * Math.PI) / 180;
  const p = (lat * Math.PI) / 180;
  const p2 = p * p;
  const p4 = p2 * p2;
  const x = l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)));
  const y = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4)));
  return [map.tx + map.k * x, map.ty - map.k * y];
}
